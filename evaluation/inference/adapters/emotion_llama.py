"""LongEmoBench adapter for the vendored official Emotion-LLaMA runtime.

``create_runtime(config).generate(video_path, prompt)`` forwards the complete
benchmark prompt to ``EmotionLLaMARuntime.analyze``. Model dependencies and
weights are loaded only on the first generation, in the upstream environment.

The official demo uses the first frame and mean-pooled HuBERT audio features;
it requires an audio track and does not sample a video's temporal progression.
No transcript is read or generated by this adapter.
"""

from __future__ import annotations

import importlib
import json
import sys
from pathlib import Path
from threading import Lock


OFFICIAL_COMMIT = "e69faadfd3824b94dd334f463cc5bbdb27229c6d"
DEFAULT_REPO = Path(__file__).resolve().parents[1] / "emollm" / "Emotion-LLaMA"
_GENERATION_KEYS = frozenset(
    {
        "temperature",
        "max_new_tokens",
        "max_length",
        "num_beams",
        "min_length",
        "top_p",
        "repetition_penalty",
        "length_penalty",
        "seed",
    }
)
_CONFIG_KEYS = frozenset(
    {
        "repo_dir",
        "repo_path",
        "config_path",
        "model_path",
        "checkpoint",
        "audio_model_path",
        "device",
        "dataset_name",
        "options",
        "generation",
    }
)


def _load_runtime_class(repo_path):
    """Import the official package, rejecting another checkout's minigpt4."""
    package = sys.modules.get("minigpt4")
    if package is not None:
        origin = getattr(package, "__file__", None)
        expected = repo_path / "minigpt4" / "__init__.py"
        if origin is None or Path(origin).resolve() != expected.resolve():
            raise RuntimeError(
                "Another minigpt4 package is already imported. Run Emotion-LLaMA "
                "in its own Python process using the official environment."
            )
    repo_string = str(repo_path)
    if repo_string not in sys.path:
        sys.path.insert(0, repo_string)
    try:
        module = importlib.import_module("minigpt4.inference.runtime")
    except ImportError as exc:
        raise RuntimeError(
            "Emotion-LLaMA dependencies could not be imported. Use a Python "
            "environment prepared from emollm/Emotion-LLaMA/environment.yaml "
            "and its demo dependencies. Original import error: {}".format(exc)
        ) from exc
    return module.EmotionLLaMARuntime


class _ContextCheckedModel:
    """Check actual multimodal embeddings before official context slicing."""

    def __init__(self, model, max_new_tokens, max_length):
        self._model = model
        self._max_new_tokens = max_new_tokens
        self._max_length = max_length

    def __getattr__(self, name):
        return getattr(self._model, name)

    def get_context_emb(self, *args, **kwargs):
        embeddings = self._model.get_context_emb(*args, **kwargs)
        needed = embeddings.shape[1] + self._max_new_tokens
        if needed > self._max_length:
            raise ValueError(
                "Emotion-LLaMA input plus generation needs {} tokens, exceeding "
                "max_length {}; reduce max_new_tokens or input text, or set a "
                "max_length supported by the base model".format(
                    needed, self._max_length
                )
            )
        return embeddings


def _install_context_guard(runtime):
    """Attach the guard when official components load, preserving lazy loading.

    The official inference lock serializes answer preparation. Temporarily proxy
    Chat.model instead of changing any model or upstream class method globally.
    The original model is restored before generation, including on errors.
    """
    original_loader = runtime._component_loader or runtime._load_components

    def load_components():
        components = original_loader()
        chat = components.chat if hasattr(components, "chat") else components[0]
        original_prepare = chat.answer_prepare

        def checked_prepare(*args, **kwargs):
            model = chat.model
            chat.model = _ContextCheckedModel(
                model, kwargs.get("max_new_tokens", 300), kwargs.get("max_length", 2000)
            )
            try:
                return original_prepare(*args, **kwargs)
            finally:
                chat.model = model

        chat.answer_prepare = checked_prepare
        return components

    runtime._component_loader = load_components


class EmotionLLaMABenchmarkRuntime:
    """Reuse one official runtime while keeping each question independent.

    ``repo_dir`` (also accepted as ``repo_path``) defaults to the vendored
    checkout. ``config_path`` defaults to
    that checkout's ``eval_configs/demo.yaml``. Explicit paths are resolved
    against the caller's working directory. ``model_path``, ``checkpoint`` and
    ``audio_model_path`` override the corresponding model paths in that YAML;
    ``options`` accepts additional official OmegaConf ``key=value`` overrides.
    ``generation`` accepts the official ``analyze`` keyword arguments only.
    The adapter never downloads or installs anything during construction.
    Upstream model loading may populate its EVA/Hugging Face caches at runtime.
    """

    def __init__(self, config):
        if not isinstance(config, dict):
            raise TypeError("Emotion-LLaMA config must be a JSON object")
        unknown = set(config) - _CONFIG_KEYS
        if unknown:
            raise ValueError(
                "Unknown Emotion-LLaMA config keys: " + ", ".join(sorted(unknown))
            )
        if "repo_dir" in config and "repo_path" in config:
            raise ValueError("Use only one of repo_dir and repo_path")
        self.repo_path = (
            Path(config.get("repo_dir", config.get("repo_path", DEFAULT_REPO)))
            .expanduser()
            .resolve()
        )
        runtime_source = self.repo_path / "minigpt4" / "inference" / "runtime.py"
        if not runtime_source.is_file():
            raise FileNotFoundError(
                "Official Emotion-LLaMA runtime not found: {}".format(runtime_source)
            )
        self.config_path = (
            Path(
                config.get("config_path", self.repo_path / "eval_configs" / "demo.yaml")
            )
            .expanduser()
            .resolve()
        )
        if not self.config_path.is_file():
            raise FileNotFoundError(
                "Emotion-LLaMA config not found: {}".format(self.config_path)
            )

        options = config.get("options", [])
        if not isinstance(options, list) or any(
            not isinstance(value, str) or "=" not in value for value in options
        ):
            raise ValueError(
                "Emotion-LLaMA options must be a list of key=value strings"
            )
        self.options = list(options)
        for key, model_key in (
            ("model_path", "llama_model"),
            ("checkpoint", "ckpt"),
            ("audio_model_path", "audio_model_path"),
        ):
            if key in config:
                path = Path(config[key]).expanduser().resolve()
                exists = path.is_file() if key == "checkpoint" else path.is_dir()
                if not exists:
                    raise FileNotFoundError(
                        "Emotion-LLaMA {} not found: {}".format(key, path)
                    )
                # JSON string quoting also handles spaces and '=' in local paths
                # safely in OmegaConf's YAML scalar parsing.
                self.options.append(
                    "model.{}={}".format(model_key, json.dumps(str(path)))
                )
        self.device = config.get("device")
        self.dataset_name = config.get("dataset_name", "feature_face_caption")
        generation = config.get("generation", {})
        if not isinstance(generation, dict):
            raise ValueError("Emotion-LLaMA generation must be a JSON object")
        unknown = set(generation) - _GENERATION_KEYS
        if unknown:
            raise ValueError(
                "Unknown Emotion-LLaMA generation options: "
                + ", ".join(sorted(unknown))
            )
        self.generation = dict(generation)
        max_new_tokens = self.generation.get("max_new_tokens", 500)
        max_length = self.generation.get("max_length", 2000)
        for key, value in (
            ("max_new_tokens", max_new_tokens),
            ("max_length", max_length),
        ):
            if isinstance(value, bool) or not isinstance(value, int) or value < 1:
                raise ValueError(
                    "Emotion-LLaMA {} must be a positive integer".format(key)
                )
        if max_new_tokens >= max_length:
            raise ValueError(
                "Emotion-LLaMA max_new_tokens must be less than max_length to leave room for video and question inputs"
            )
        self.metadata = {
            "implementation": "official EmotionLLaMARuntime.analyze",
            "vendored_commit": OFFICIAL_COMMIT,
            "repo_dir": str(self.repo_path),
            "visual_input": "first video frame only",
            "audio_input": "full audio track; mean-pooled final HuBERT layer",
            "face_feature": "zero-filled official demo feature slot",
            "temporal_feature": "zero-filled official demo feature slot",
            "requires_audio_track": True,
            "transcript": "only text explicitly supplied in the benchmark prompt",
            "context_policy": "error before official truncation if actual input embeddings plus output budget exceed max_length",
        }
        self._runtime = None
        self._load_lock = Lock()

    def _get_runtime(self):
        if self._runtime is None:
            with self._load_lock:
                if self._runtime is None:
                    runtime_class = _load_runtime_class(self.repo_path)
                    self._runtime = runtime_class(
                        cfg_path=str(self.config_path),
                        options=self.options,
                        device=self.device,
                        dataset_name=self.dataset_name,
                    )
                    _install_context_guard(self._runtime)
        return self._runtime

    def generate(self, video_path: str, prompt: str) -> str:
        """Pass the supplied question unchanged to the official video runtime."""
        if not isinstance(prompt, str) or not prompt.strip():
            raise ValueError("prompt must be a non-empty string")
        video = Path(video_path).expanduser().resolve()
        if not video.is_file():
            raise FileNotFoundError("Video file does not exist: {}".format(video))
        answer = self._get_runtime().analyze(str(video), prompt, **self.generation)
        if not isinstance(answer, str):
            raise TypeError(
                "Official Emotion-LLaMA runtime returned a non-string answer"
            )
        return answer


def create_runtime(config: dict) -> EmotionLLaMABenchmarkRuntime:
    return EmotionLLaMABenchmarkRuntime(config)


